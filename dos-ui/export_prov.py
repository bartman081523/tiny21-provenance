"""Calibrate the familiarity axis on the SHIPPED weights and write PROV.H.

The direction is fitted on the quantised TINY.BIN (the same weights the DOS
binary runs), not on the float checkpoint, so the exported numbers apply to
the C build.

    PYTHONPATH=/path/to/provenance-audit python dos-ui/export_prov.py
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, REPO)

from provenance.tiny_v2 import TinyV2Backend  # noqa: E402
from provenance.run_tiny import REAL, NONCE, FAM_TEMPLATE  # noqa: E402
from provenance_audit.core import loo_axis  # noqa: E402


def main() -> int:
    b = TinyV2Backend(os.path.join(REPO, "dos", "TINY.BIN"),
                      os.path.join(REPO, "training"))
    Hf = np.stack([b.capture(b.encode(FAM_TEMPLATE.format(X=X))) for X in REAL])
    Hn = np.stack([b.capture(b.encode(FAM_TEMPLATE.format(X=X))) for X in NONCE])
    ax = loo_axis(Hf, Hn)
    d = np.asarray(ax["direction"], dtype=np.float64)
    thr = float(ax["threshold"])
    print(f"layer {ax['layer']}  acc {ax['acc']:.3f}  p {ax['p']:.4f}  "
          f"thr {thr:+.3f}  ||d|| {np.linalg.norm(d):.4f}")

    # sanity: the same rule on the training cells
    sc = np.concatenate([Hf[:, ax["layer"]] @ d, Hn[:, ax["layer"]] @ d]) - thr
    print(f"  familiar > 0: {int((sc[:len(REAL)] > 0).sum())}/{len(REAL)}   "
          f"novel < 0: {int((sc[len(REAL):] < 0).sum())}/{len(NONCE)}")

    def carr(v, name):
        lines = [f"static const float {name}[{len(v)}] = {{"]
        for i in range(0, len(v), 6):
            lines.append("    " + ", ".join("%.7ff" % x for x in v[i:i + 6])
                         + ",")
        lines.append("};")
        return "\n".join(lines)

    out = os.path.join(HERE, "PROV.H")
    with open(out, "w", encoding="ascii") as fh:
        fh.write("/* generated by dos-ui/export_prov.py -- do not edit */\n")
        fh.write(f"/* TINY.BIN quantised weights, layer {ax['layer']}, "
                 f"loo acc {ax['acc']:.3f}, p {ax['p']:.4f} */\n")
        fh.write(f"#define PROV_D {len(d)}\n")
        fh.write("#define PROV_MARGIN 1.0f   /* dead zone: near the boundary "
                 "the panel shows \"--\" */\n")
        fh.write(f"#define PROV_LAYER {ax['layer']}\n")
        fh.write(f"#define PROV_THR {thr:.7f}f\n")
        fh.write(carr(d, "PROV_DIR") + "\n")
    print(f"written {out}")
    json.dump({"layer": ax["layer"], "acc": ax["acc"], "p": ax["p"],
               "threshold": thr, "n": ax["n"]},
              open(os.path.join(HERE, "prov_calibration.json"), "w"), indent=1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
